// https://github.com/microsoft/TypeScript/wiki/Using-the-Compiler-API
import ts from "typescript";
// https://nodejs.org/docs/latest/api/fs.html
import fs from "node:fs";
// https://cheerio.js.org/docs/intro/
import * as cheerio from "cheerio";

class TypeAliasError extends Error {}

interface Handler {
  method: string;
  params: string;
  result?: string;
}

interface Context {
  fileHandle: number;
  // dataclasses by name
  dataClasses: Record<string, DataClass>;
  // Handlers by Parameter class name
  handlers: Record<string, Handler>;
}
interface DataClass {
  node: ts.Node;
  subclasses: string[];
  name: string;
  fields: Field[];
}

interface Field {
  optional: boolean;
  name: string;
  comment: string;
  type: ts.TypeNode;
}

function handlers() {
  const $ = cheerio.load(fs.readFileSync("lsp-docs/spec.html"));
  let current: Partial<Handler> = {};
  const table: Handler[] = [];

  $("li").each(function () {
    const content = $(this).text().trim();
    const regex = /^(method|params): ([\S]+)/;
    const match = content.match(regex);
    const resultRegex = /^result: (.+)$/;
    const resultMatch = content.match(resultRegex);
    if (match) {
      const value = match[2];
      const trimmed = value.match(/[\w/$]+/)![0];
      if (match[1] === "method") {
        if (current.method) {
          table.push(current as Handler);
          current = {};
        }
        current.method = trimmed;
      } else if (match[1] === "params") {
        current.params = trimmed;
      }
    } else if (resultMatch) {
      current.result = resultMatch[1];
    }
  });
  return table;
}

function main() {
  const header = `# Autogenerated by: code-gen/main.js
from dataclasses import dataclass
from dataclass_wizard import Alias, JSONWizard
from enum import Enum
from typing import Any, ClassVar, Dict, Literal

# items we haven't implemented a parser for yet
type decimal = float
type integer = int
type uinteger = int
@dataclass
class Empty:\n\tpass
`;

  const types = "lsp-docs/types.ts";
  const target = "src/goose/generated.py";

  const table: Record<string, Handler> = Object.fromEntries(
    handlers().map((c) => [c.params, c]),
  );
  const handle = fs.openSync(target, "w");
  fs.writeSync(handle, header);

  const program = ts.createProgram([types], {});
  const ast = program.getSourceFile(types)!;

  const aliases: Record<string, ts.TypeAliasDeclaration> = {};
  const dataClasses: Record<string, DataClass> = {};
  const enums: ts.NamespaceDeclaration[] = [];
  ts.forEachChild(ast, (node) => {
    if (node?.kind === undefined) return;
    if (node.kind === ts.SyntaxKind.InterfaceDeclaration) {
      const dc = processInterface(node);
      dataClasses[dc.name] = dc;
    } else if (node.kind == ts.SyntaxKind.TypeAliasDeclaration) {
      const decl = node as ts.TypeAliasDeclaration;
      aliases[decl.name.escapedText as string] = decl;
    } else if (node.kind == ts.SyntaxKind.ModuleDeclaration) {
      enums.push(node as ts.NamespaceDeclaration);
    } else {
      return;
    }
  });
  const ctx: Context = {
    fileHandle: handle,
    dataClasses: dataClasses,
    handlers: table,
  };
  for (const dc of Object.values(dataClasses)) {
    writeDataClass(ctx, dc);
  }
  // reorder dc class fields putting optional last
  // merge dc classes that have subclasses
  // merge dataclasses together
  // come up with a list of

  for (const node of enums) {
    // enum trumps alias
    delete aliases[node.name.escapedText as string];
    processEnum(handle, node);
  }
  for (const node of Object.values(aliases)) {
    processAlias(handle, node);
  }
}

function toComment(nodesOrText: any) {
  if (typeof nodesOrText === "string") return nodesOrText;
  if (!nodesOrText) return "";
  return nodesOrText.map((node) => node.text ?? node.name.escapedText).join("");
}
function writeDataClass(ctx: Context, dc: DataClass) {
  for (const cls of dc.subclasses) {
    const lookup = ctx.dataClasses[cls];
    dc.fields.push(...lookup.fields);
  }

  dc.fields.sort((a, b) =>
    a.optional === b.optional
      ? a.name.localeCompare(b.name)
      : Number(a.optional) - Number(b.optional),
  );

  if (dc.node.typeParameters) {
    const params = dc.node.typeParameters
      .map((p) => p.name.escapedText)
      .join(",");
    fs.writeSync(ctx.fileHandle, `@dataclass\nclass ${dc.name}[${params}]:\n`);
  } else {
    fs.writeSync(ctx.fileHandle, `@dataclass\nclass ${dc.name}:\n`);
  }

  const handler = ctx.handlers[dc.name];
  if (handler) {
    fs.writeSync(
      ctx.fileHandle,
      `\tclass Meta(JSONWizard.Meta): \n\t\ttag = '${handler.method}'\n`,
    );
  } else if (dc.node.jsDoc) {
    fs.writeSync(
      ctx.fileHandle,
      `\t"""${toComment(dc.node.jsDoc[0].comment)}"""\n`,
    );
  } else if (!dc.fields.length) {
    fs.writeSync(ctx.fileHandle, `\tpass\n`);
  }

  for (const field of dc.fields) {
    let type;
    try {
      type = to_python_type_name(field.type);
    } catch (e) {
      if (e instanceof TypeAliasError) {
        type = capitalize(field.name);
        fs.writeSync(ctx.fileHandle, `\t@dataclass\n`);
        fs.writeSync(ctx.fileHandle, `\tclass ${type}:\n`);
        for (const member of field.type.members) {
          const label = member.name.escapedText;
          fs.writeSync(
            ctx.fileHandle,
            `\t\t${label}: ${to_python_type_name(member.type)} \n`,
          );
        }
        return;
      } else {
        throw e;
      }
    }

    const assignment =
      field.name === "from"
        ? `= Alias("from")`
        : field.optional
          ? "= None"
          : "";

    fs.writeSync(
      ctx.fileHandle,
      `\t${field.name === "from" ? "from_" : field.name}: ${type}${field.optional ? "| None" : ""} ${assignment}\n`,
    );
    if (field.comment) {
      fs.writeSync(ctx.fileHandle, `\t"""${field.comment}"""\n`);
    }
  }
}

function processAlias(handle: number, node: ts.TypeAliasDeclaration) {
  // skip primitives
  if (isLowercase((node.name.escapedText as string)[0])) return;
  const alias = node.name.escapedText;
  try {
    fs.writeSync(handle, `type ${alias} = ${to_python_type_name(node.type)}\n`);
  } catch (e) {
    if (e instanceof TypeAliasError) {
      fs.writeSync(handle, `@dataclass\n`);
      fs.writeSync(handle, `class ${alias}:\n`);
      for (const member of node.type.members) {
        const label = member.name.escapedText;
        fs.writeSync(
          handle,
          `\t${label}: ${to_python_type_name(member.type)}\n`,
        );
      }
    } else {
      throw e;
    }
  }
}

function processInterface(node: any): DataClass {
  const name = node?.name?.escapedText;
  const fields: Field[] = [];
  const subclasses: string[] = node.heritageClauses
    ? node.heritageClauses.flatMap((clause) =>
        clause.types.map((node) => node.expression.escapedText),
      )
    : [];
  for (const member of node.members) {
    let name = member.name?.escapedText;
    if (!name) {
      continue;
    }
    const comment = member.jsDoc ? member.jsDoc[0].comment : "";
    const type = member.type;
    const optional = !!member.questionToken;
    fields.push({ name, type, comment, optional });
  }
  return { kind: "class", name, node, fields, subclasses };
}

function processEnum(handle, node) {
  const name = node.name.escapedText;
  fs.writeSync(handle, `class ${name}(Enum):\n`);

  if (node.jsDoc) {
    fs.writeSync(handle, `\t"""${node.jsDoc[0].comment}"""\n`);
  } else if (!node.body.statements.length) {
    fs.writeSync(handle, `\tpass\n`);
  }
  for (const child of node.body.statements) {
    const declaration = child.declarationList.declarations[0];
    let name = declaration.name.escapedText;
    if (name === "None") name = "None_";

    const value = declaration.initializer.text;
    const kind = declaration.initializer.kind;
    if (kind === ts.SyntaxKind.NumericLiteral) {
      fs.writeSync(handle, `\t${name} = ${value} \n`);
    } else if (kind === ts.SyntaxKind.StringLiteral) {
      fs.writeSync(handle, `\t${name} = '${value}'\n`);
    }
    // UnaryExpression
    else if (
      kind === ts.SyntaxKind.PrefixUnaryExpression &&
      declaration.initializer.operator === ts.SyntaxKind.MinusToken
    ) {
      fs.writeSync(
        handle,
        `\t${name} = -${declaration.initializer.operand.text} \n`,
      );
    } else if (kind === ts.SyntaxKind.AsExpression) {
      const kind = declaration.initializer.expression.kind;
      const value = declaration.initializer.expression.text;

      if (kind === ts.SyntaxKind.NumericLiteral) {
        fs.writeSync(handle, `\t${name} = ${value} \n`);
      } else if (kind === ts.SyntaxKind.StringLiteral) {
        fs.writeSync(handle, `\t${name} = '${value}'\n`);
      } else {
        console.log("enum", ts.SyntaxKind[kind]);
      }
    } else {
      console.log("enum", ts.SyntaxKind[kind]);
    }
  }
}

function to_python_type_name(node: ts.TypeNode): string {
  // @ts-ignore
  const type = node.typeName?.escapedText;
  if (type) return type;
  else if (node.kind === ts.SyntaxKind.UnionType)
    return node.types.map(to_python_type_name).join(" | ");
  else if (node.kind === ts.SyntaxKind.BooleanKeyword) return "bool";
  else if (node.kind === ts.SyntaxKind.StringKeyword) return "str";
  else if (node.kind === ts.SyntaxKind.NullKeyword) return "None";
  else if (node.kind === ts.SyntaxKind.ArrayType) {
    const el = to_python_type_name(node.elementType);
    return `list[${el}]`;
  } else if (node.kind === ts.SyntaxKind.TupleType) {
    const types = node.elements.map(to_python_type_name).join(",");

    return `tuple[${types}]`;
  } else if (node.kind === ts.SyntaxKind.LiteralType) {
    if (node.literal.kind === ts.SyntaxKind.NumericLiteral)
      return `Literal[${node.literal.text}]`;
    else if (node.literal.kind === ts.SyntaxKind.StringLiteral)
      return `Literal["${node.literal.text}"]`;
    else if (node.literal.kind === ts.SyntaxKind.NullKeyword) return "None";
    else {
      console.log("literal", ts.SyntaxKind[node.literal.kind]);
      return "TODO";
    }
  } else if (node.kind === ts.SyntaxKind.ParenthesizedType) {
    return to_python_type_name(node.type);
  } else if (node.kind === ts.SyntaxKind.TypeLiteral) {
    if (node.members.length === 0) {
      return "Empty";
    } else if (
      node.members.length === 1 &&
      node.members[0].kind === ts.SyntaxKind.IndexSignature
    ) {
      const sig = node.members[0];

      const key = to_python_type_name(sig.parameters[0].type);
      const value = to_python_type_name(sig.type);
      return `Dict[${key},${value}]`;
    } else {
      // we need to handle this an inline alias
      throw new TypeAliasError();
    }
  } else if (node.kind === ts.SyntaxKind.TypeQuery) {
    return node.exprName.escapedText;
  } else if (node.kind === ts.SyntaxKind.IntersectionType) {
    // ty supports this
    // pyright and other typecheckers don't
    return node.types.map((ty) => ty.typeName.escapedText).join(" & ");
  } else {
    console.log("type", ts.SyntaxKind[node.kind]);
    return "TODO";
  }
}

function isLowercase(c) {
  return c === c.toLowerCase();
}

function capitalize(s) {
  return s[0].toUpperCase() + s.slice(1);
}

main();
