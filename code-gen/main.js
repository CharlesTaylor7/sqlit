// https://github.com/microsoft/TypeScript/wiki/Using-the-Compiler-API
import ts from "typescript"
// https://nodejs.org/docs/latest/api/fs.html
import fs from "node:fs";
// https://cheerio.js.org/docs/intro/
import * as cheerio from 'cheerio';

class TypeAliasError extends Error {
}

main()
function handlers() {
  const $ = cheerio.load(fs.readFileSync("lsp-docs/spec.html"));
  let current = {};
  const table = []

  $("li").each(function() {
    const content = $(this).text().trim()
    const regex = /^(method|params): ([\S]+)/
    const match = content.match(regex);
    const resultRegex = /^result: (.+)$/
    const resultMatch = content.match(resultRegex);
    if (match) {
      const value = match[2];
      const trimmed = value.match(/[\w/$]+/)[0];
      if (match[1] === "method") {
        if (current.method) {
          table.push(current);
          current = {};
        }
        current.method = trimmed;
      }
      else if (match[1] === "params") {
        current.params = trimmed;
      }
    }
    else if (resultMatch) {
      current.result = resultMatch[1];
    }
  });
  return table;
}


function main() {
  const header = `# Autogenerated by: code-gen/main.js
from dataclasses import dataclass
from dataclass_wizard import Alias, JSONWizard
from enum import Enum
from typing import Any, ClassVar, Dict, Literal

# items we haven't implemented a parser for yet
type TODO = Any
type decimal = float
type integer = int
type uinteger = int
@dataclass
class Empty():\n\tpass
`

  const types = "lsp-docs/types.ts"
  const target = "src/goose/generated.py"

  const table = Object.fromEntries(handlers().map(c => [c.params, c.method]));
  const handle = fs.openSync(target, 'w');
  fs.writeSync(handle, header)

  const program = ts.createProgram([types], {})
  const ast = program.getSourceFile(types);

  const aliases = {};
  const enums = [];
  ts.forEachChild(ast, node => {
    if (node?.kind === undefined) return;
    const kind = ts.SyntaxKind[node.kind];

    if (kind === "InterfaceDeclaration") {
      processInterface(handle, node, table)

    }
    // TODO we need to merge type aliases and namepsaces when the namepsace is an enum for the alias. Json wizard can handle that.
    else if (kind == "TypeAliasDeclaration") {
      aliases[node.name.escapedText] = node;
    }
    else if (kind == "ModuleDeclaration") {
      enums.push(node);
    }
    else {
      return;
    }
  })

  for (const node of enums) {
    // enum trumps alias
    delete aliases[node.name.escapedText]
    processEnum(handle, node);
  }
  for (const node of Object.values(aliases)) {
    processAlias(handle, node);
  }
}


function processAlias(handle, node) {
  // skip primitives
  if (isLowercase(node.name.escapedText[0])) return;
  const alias = node.name.escapedText
  try {
    fs.writeSync(handle, `type ${alias} = ${to_python_type_name(node.type)}\n`)
  } catch (e) {
    if (e instanceof TypeAliasError) {
      fs.writeSync(handle, `@dataclass\n`)
      fs.writeSync(handle, `class ${alias}:\n`)
      for (const member of node.type.members) {
        const label = member.name.escapedText;
        fs.writeSync(handle, `\t${label}: ${to_python_type_name(member.type)}\n`)
      }
    }
    else {
      throw e
    }
  }
}

function processInterface(handle, node, table) {
  const name = node?.name?.escapedText;
  if (node.typeParameters) {
    const params = node.typeParameters.map(p => p.name.escapedText).join(",");
    fs.writeSync(handle, `@dataclass\nclass ${name} [${params}]: \n`)
  }
  else if (node.heritageClauses) {
    const subclasses = node.heritageClauses[0].types.map(node =>
      node.expression.escapedText
    ).join(", ");
    fs.writeSync(handle, `@dataclass\nclass ${name} (${subclasses}): \n`)
  }

  else {
    fs.writeSync(handle, `@dataclass\nclass ${name}: \n`)
  }

  const tag = table[name];
  if (tag) {
    fs.writeSync(handle, `\tclass Meta(JSONWizard.Meta): \n\t\ttag = '${tag}'\n`)
  }
  else if (node.jsDoc) {
    fs.writeSync(handle, `\t"""${node.jsDoc[0].comment}"""\n`)
  }
  else if (!node.members.length) {
    fs.writeSync(handle, `\tpass\n`)
  }
  for (const member of node.members) {
    let field = member.name?.escapedText
    if (!field) {
      continue
    }
    let type;
    try {
      type = to_python_type_name(member.type);
      // TODO: reorder members so optional ones are last
    } catch (e) {
      if (e instanceof TypeAliasError) {
        type = capitalize(field)
        fs.writeSync(handle, `\t@dataclass\n`)
        fs.writeSync(handle, `\tclass ${type}:\n`)
        for (const member of node.type.members) {
          const label = member.name.escapedText;
          fs.writeSync(handle, `\t\t${label}: ${to_python_type_name(member.type)} \n`)
        }
        return;
      } else {
        throw e;
      }
    }

    const optional = member.questionToken ? " | None" : ""

    const assignment = field === "from" ? `= Alias("from")` : member.questionToken ? "= None" : "";
    
    fs.writeSync(handle, `\t${field === "from" ? "from_" : field}: ${type}${optional} ${assignment}\n`)
    if (member.jsDoc) {
      fs.writeSync(handle, `\t"""${member.jsDoc[0].comment}"""\n`)
    }
  }
}


function processEnum(handle, node) {
  const name = node.name.escapedText
  fs.writeSync(handle, `class ${name}(Enum):\n`)

  if (node.jsDoc) {
    fs.writeSync(handle, `\t"""${node.jsDoc[0].comment}"""\n`)
  }
  else if (!node.body.statements.length) {
    fs.writeSync(handle, `\tpass\n`)
  }
  for (const child of node.body.statements) {
    const declaration = child.declarationList.declarations[0];
    let name = declaration.name.escapedText;
    if (name === "None") name = "None_";

    const value = declaration.initializer.text;
    const kind = declaration.initializer.kind
    if (kind === ts.SyntaxKind.NumericLiteral) {
      fs.writeSync(handle, `\t${name} = ${value} \n`)
    }
    else if (kind === ts.SyntaxKind.StringLiteral) {
      fs.writeSync(handle, `\t${name} = '${value}'\n`)
    }
    // UnaryExpression
    else if (kind === ts.SyntaxKind.PrefixUnaryExpression && declaration.initializer.operator === ts.SyntaxKind.MinusToken) {
      fs.writeSync(handle, `\t${name} = -${declaration.initializer.operand.text} \n`)
    }
    else if (kind === ts.SyntaxKind.AsExpression) {
      const kind = declaration.initializer.expression.kind;
      const value = declaration.initializer.expression.text;

      if (kind === ts.SyntaxKind.NumericLiteral) {
        fs.writeSync(handle, `\t${name} = ${value} \n`)
      }
      else if (kind === ts.SyntaxKind.StringLiteral) {
        fs.writeSync(handle, `\t${name} = '${value}'\n`)
      }
      else {
        console.log("enum", ts.SyntaxKind[kind])
      }
    }
    else {
      console.log("enum", ts.SyntaxKind[kind])
    }
  }
}


function to_python_type_name(node) {
  const type = node.typeName?.escapedText
  if (type) return type;
  else if (node.kind === ts.SyntaxKind.UnionType) return node.types.map(to_python_type_name).join(" | ");

  else if (node.kind === ts.SyntaxKind.BooleanKeyword) return "bool";
  else if (node.kind === ts.SyntaxKind.StringKeyword) return "str"
  else if (node.kind === ts.SyntaxKind.NullKeyword) return "None"
  else if (node.kind === ts.SyntaxKind.ArrayType) {
    const el = to_python_type_name(node.elementType);
    return `list[${el}]`;
  }
  else if (node.kind === ts.SyntaxKind.TupleType) {
    const types = node.elements.map(to_python_type_name).join(",");

    return `tuple[${types}]`
  }
  else if (node.kind === ts.SyntaxKind.LiteralType) {
    if (node.literal.kind === ts.SyntaxKind.NumericLiteral) return `Literal[${node.literal.text}]`;
    else if (node.literal.kind === ts.SyntaxKind.StringLiteral) return `Literal["${node.literal.text}"]`;
    else if (node.literal.kind === ts.SyntaxKind.NullKeyword) return "None";
    else {
      console.log("literal", ts.SyntaxKind[node.literal.kind])
      return "TODO"
    }
  }

  else if (node.kind === ts.SyntaxKind.ParenthesizedType) {
    return to_python_type_name(node.type);
  }
  else if (node.kind === ts.SyntaxKind.TypeLiteral) {
    if (node.members.length === 0) {
      return "Empty"
    }
    else if (node.members.length === 1 && node.members[0].kind === ts.SyntaxKind.IndexSignature) {
      const sig = node.members[0];

      const key = to_python_type_name(sig.parameters[0].type)
      const value = to_python_type_name(sig.type)
      return `Dict[${key},${value}]`
    }
    else {
      // we need to handle this an inline alias
      throw new TypeAliasError()
    }
  }

  else if (node.kind === ts.SyntaxKind.TypeQuery) {
    return node.exprName.escapedText;
  }
  else if (node.kind === ts.SyntaxKind.IntersectionType) {
    // ty supports this
    // pyright and other typecheckers don't 
    return node.types.map(ty => ty.typeName.escapedText).join(" & ")
  }
  else {
    console.log("type", ts.SyntaxKind[node.kind]);
    return "TODO"
  }
}

function isLowercase(c) {
  return c === c.toLowerCase();
}
function capitalize(s) {
  return s[0].toUpperCase() + s.slice(1);
}

